import { ERDSchema, TableNode, Column, Relationship, MigrationCommand, SchemaStep } from '../types/erd';

export type SqlDialect = 'postgres' | 'mysql' | 'sqlite';

export function generateSqlDDL(schema: ERDSchema, dialect: SqlDialect = 'postgres'): string {
  const lines: string[] = [];
  const headerComment = dialect === 'postgres' 
    ? `-- Generated by Relatia for PostgreSQL\n-- Database Schema: ${schema.title}\n-- Created: ${new Date().toISOString()}\n\n`
    : dialect === 'mysql'
    ? `-- Generated by Relatia for MySQL\n-- Database Schema: ${schema.title}\n-- Created: ${new Date().toISOString()}\n\n`
    : `-- Generated by Relatia for SQLite\n-- Database Schema: ${schema.title}\n-- Created: ${new Date().toISOString()}\n\n`;

  lines.push(headerComment);

  // Map of column types per dialect
  const mapType = (type: string, length?: string, decimals?: string, d?: SqlDialect): string => {
    let t = type.toUpperCase().trim();

    if (t === 'DECIMAL') {
      if (decimals !== undefined && decimals.trim()) {
        const prec = length && length.trim() ? length.trim() : '10';
        t = `DECIMAL(${prec}, ${decimals.trim()})`;
      } else if (length && length.trim()) {
        t = length.includes('(') ? length : `DECIMAL(${length.trim()})`;
      } else {
        t = 'DECIMAL(10, 2)';
      }
    } else if (length && length.trim() && !t.includes('(')) {
      t = `${t}(${length.trim()})`;
    }

    if (d === 'sqlite') {
      if (t.includes('INT')) return 'INTEGER';
      if (t.includes('CHAR') || t.includes('TEXT') || t.includes('DATE') || t.includes('TIME')) return 'TEXT';
      if (t.includes('BOOL')) return 'INTEGER';
      if (t.includes('DECIMAL') || t.includes('FLOAT') || t.includes('NUMERIC')) return 'REAL';
      return t;
    }
    if (d === 'mysql') {
      if (t === 'BOOLEAN') return 'TINYINT(1)';
      if (t === 'TIMESTAMP') return 'DATETIME';
      return t;
    }
    // PostgreSQL default: DATETIME maps to TIMESTAMP
    if (t === 'DATETIME') return 'TIMESTAMP';
    return t;
  };

  const databases = schema.databases || [];

  const renderTableDDL = (table: TableNode) => {
    const tableLines: string[] = [];
    tableLines.push(`-- Table: ${table.name}`);
    tableLines.push(`CREATE TABLE ${table.name} (`);

    const colDefs: string[] = [];
    const pkCols: string[] = [];

    table.columns.forEach((col: Column) => {
      let typeStr = mapType(col.type, col.length, col.decimals, dialect);

      // Auto increment handling
      if (col.isAutoIncrement || col.modifiers?.includes('AUTO_INCREMENT')) {
        if (dialect === 'postgres') {
          if (typeStr.startsWith('BIGINT')) typeStr = 'BIGSERIAL';
          else if (typeStr.startsWith('INT')) typeStr = 'SERIAL';
          else typeStr += ' GENERATED ALWAYS AS IDENTITY';
        } else if (dialect === 'mysql') {
          typeStr += ' AUTO_INCREMENT';
        }
      }

      let def = `  ${col.name} ${typeStr}`;

      if (col.isPK) {
        pkCols.push(col.name);
      }

      if (!col.isNullable && !col.isPK) {
        def += ' NOT NULL';
      } else if (col.modifiers?.includes('NULL') && !col.isPK) {
        def += ' NULL';
      }

      if (col.isUnique && !col.isPK) {
        def += ' UNIQUE';
      }

      if (col.defaultValue && col.defaultValue.trim()) {
        def += ` DEFAULT ${col.defaultValue}`;
      }

      colDefs.push(def);
    });

    // Primary key constraint
    if (pkCols.length > 0) {
      colDefs.push(`  CONSTRAINT pk_${table.name} PRIMARY KEY (${pkCols.join(', ')})`);
    }

    // Inline Foreign keys for this table based on relationships where this table is source
    const tableForeignRels = schema.relationships.filter(
      r => r.fromTableId === table.id && r.fromColumnId && r.toColumnId
    );

    tableForeignRels.forEach((rel: Relationship) => {
      const targetTable = schema.tables.find(t => t.id === rel.toTableId);
      const fromCol = table.columns.find(c => c.id === rel.fromColumnId);
      const toCol = targetTable?.columns.find(c => c.id === rel.toColumnId);

      if (targetTable && fromCol && toCol) {
        const fkConstraintName = `fk_${table.name}_${fromCol.name}`;
        const deleteAction = rel.onDelete || fromCol.onDelete || 'CASCADE';
        colDefs.push(
          `  CONSTRAINT ${fkConstraintName} FOREIGN KEY (${fromCol.name}) REFERENCES ${targetTable.name} (${toCol.name}) ON DELETE ${deleteAction}`
        );
      }
    });

    tableLines.push(colDefs.join(',\n'));
    tableLines.push(');\n');
    return tableLines.join('\n');
  };

  if (databases.length > 0) {
    databases.forEach(db => {
      lines.push(`-- ==========================================================`);
      lines.push(`-- DATABASE: ${db.name}`);
      if (dialect === 'mysql') {
        lines.push(`CREATE DATABASE IF NOT EXISTS \`${db.name}\`;`);
        lines.push(`USE \`${db.name}\`;\n`);
      } else if (dialect === 'postgres') {
        lines.push(`-- CREATE DATABASE "${db.name}";`);
        lines.push(`-- \\connect "${db.name}";\n`);
      }
      lines.push(`-- ==========================================================\n`);

      const dbTables = schema.tables.filter(t => t.databaseId === db.id);
      dbTables.forEach(table => {
        lines.push(renderTableDDL(table));
      });
    });

    // Any unassigned tables
    const unassignedTables = schema.tables.filter(t => !t.databaseId || !databases.some(d => d.id === t.databaseId));
    if (unassignedTables.length > 0) {
      lines.push(`-- ==========================================================`);
      lines.push(`-- TABLAS GENERALES`);
      lines.push(`-- ==========================================================\n`);
      unassignedTables.forEach(table => {
        lines.push(renderTableDDL(table));
      });
    }
  } else {
    for (const table of schema.tables) {
      lines.push(renderTableDDL(table));
    }
  }

  return lines.join('\n');
}

export function generateCommandSql(cmd: MigrationCommand, dialect: SqlDialect = 'postgres'): string {
  if (cmd.sqlRaw) {
    return cmd.sqlRaw.endsWith(';') ? cmd.sqlRaw : `${cmd.sqlRaw};`;
  }

  switch (cmd.type) {
    case 'ADD_COLUMN':
      return `ALTER TABLE ${cmd.tableName} ADD COLUMN ${cmd.columnName || 'new_col'} ${cmd.columnType || 'VARCHAR(255)'};`;
    case 'DROP_COLUMN':
      return `ALTER TABLE ${cmd.tableName} DROP COLUMN ${cmd.columnName || 'col_name'};`;
    case 'MODIFY_COLUMN':
      if (dialect === 'postgres') {
        return `ALTER TABLE ${cmd.tableName} ALTER COLUMN ${cmd.columnName} TYPE ${cmd.columnType};`;
      } else if (dialect === 'mysql') {
        return `ALTER TABLE ${cmd.tableName} MODIFY COLUMN ${cmd.columnName} ${cmd.columnType};`;
      } else {
        return `-- SQLite does not directly support ALTER COLUMN. Requires table recreation or migration tool.`;
      }
    case 'RENAME_COLUMN':
      return `ALTER TABLE ${cmd.tableName} RENAME COLUMN ${cmd.columnName} TO ${cmd.constraintName || 'new_name'};`;
    case 'ADD_CONSTRAINT':
      return `ALTER TABLE ${cmd.tableName} ADD CONSTRAINT ${cmd.constraintName || 'chk_name'} ${cmd.constraintDefinition || 'CHECK (1=1)'};`;
    case 'DROP_CONSTRAINT':
      return `ALTER TABLE ${cmd.tableName} DROP CONSTRAINT ${cmd.constraintName || 'constraint_name'};`;
    case 'CREATE_INDEX':
      return `CREATE INDEX ${cmd.constraintName || `idx_${cmd.tableName}_${cmd.columnName}`} ON ${cmd.tableName} (${cmd.columnName || 'id'});`;
    case 'CUSTOM_SQL':
    default:
      return cmd.sqlRaw || `-- Custom step in ${cmd.tableName}`;
  }
}

export function generateTimelineMigrationSql(steps: SchemaStep[], dialect: SqlDialect = 'postgres'): string {
  const lines: string[] = [
    `-- ==========================================================`,
    `-- LÍNEA DE TIEMPO DE MIGRACIONES DE ESQUEMA (DATABASE TIMELINE)`,
    `-- Dialecto: ${dialect.toUpperCase()}`,
    `-- Generado: ${new Date().toISOString()}`,
    `-- Total de pasos evolutivos: ${steps.length}`,
    `-- ==========================================================\n`,
  ];

  steps.forEach((step, idx) => {
    lines.push(`-- ----------------------------------------------------------`);
    lines.push(`-- PASO ${step.stepNumber}: ${step.version} - ${step.title}`);
    lines.push(`-- Fecha de registro: ${step.createdAt}`);
    if (step.description) {
      lines.push(`-- Descripción: ${step.description}`);
    }
    lines.push(`-- ----------------------------------------------------------`);

    if (step.stepNumber === 0) {
      lines.push(`-- (Paso 0: Esquema Inicial CREATE TABLE ejecutado)\n`);
    } else {
      if (step.commands.length === 0) {
        lines.push(`-- Sin comandos adicionales registrados en este paso.\n`);
      } else {
        step.commands.forEach((cmd: MigrationCommand) => {
          lines.push(`-- Acción: ${cmd.description || cmd.type}`);
          lines.push(generateCommandSql(cmd, dialect));
        });
        lines.push('');
      }
    }
  });

  return lines.join('\n');
}

